CREATE TABLE IF NOT EXISTS economic_indicators (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(50)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    unit              VARCHAR(20)  NOT NULL,
    frequency         VARCHAR(20)  NOT NULL,
    source            VARCHAR(20)  NOT NULL,
    source_stat_code  VARCHAR(50)  NOT NULL,
    source_item_code  VARCHAR(50),
    description       TEXT,
    why_it_matters    TEXT,
    related_term_id   BIGINT,
    display_order     INTEGER      NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    deleted_at        TIMESTAMP(6),
    CONSTRAINT uk_economic_indicators_code  UNIQUE (code),
    CONSTRAINT fk_economic_indicators_term  FOREIGN KEY (related_term_id) REFERENCES investment_terms(id)
);

CREATE TABLE IF NOT EXISTS indicator_observations (
    id           BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_id BIGINT         NOT NULL,
    observed_at  DATE           NOT NULL,
    value        NUMERIC(19, 6) NOT NULL,
    created_at   TIMESTAMP(6)   NOT NULL,
    updated_at   TIMESTAMP(6)   NOT NULL,
    deleted_at   TIMESTAMP(6),
    CONSTRAINT uk_indicator_observation              UNIQUE (indicator_id, observed_at),
    CONSTRAINT fk_indicator_observations_indicator   FOREIGN KEY (indicator_id) REFERENCES economic_indicators(id)
);
CREATE INDEX IF NOT EXISTS idx_indicator_observed_at ON indicator_observations (indicator_id, observed_at DESC);


-- ---------------------------------------------------------------------
-- Knowledge: 공시 (DART)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS dart_corps (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corp_code   VARCHAR(8)   NOT NULL,
    corp_name   VARCHAR(200) NOT NULL,
    stock_code  VARCHAR(10),
    stock_id    BIGINT,
    modify_date DATE,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    deleted_at  TIMESTAMP(6),
    CONSTRAINT uk_dart_corps_corp_code UNIQUE (corp_code),
    CONSTRAINT fk_dart_corps_stock     FOREIGN KEY (stock_id) REFERENCES stocks(id)
);

CREATE TABLE IF NOT EXISTS disclosures (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corp_code       VARCHAR(8)   NOT NULL,
    corp_name       VARCHAR(200) NOT NULL,
    stock_id        BIGINT,
    receipt_no      VARCHAR(14)  NOT NULL,
    report_name     VARCHAR(500) NOT NULL,
    disclosure_type VARCHAR(20)  NOT NULL,
    submitted_at    TIMESTAMP(6) NOT NULL,
    submitter_name  VARCHAR(200),
    remark          VARCHAR(20),
    dart_url        VARCHAR(500) NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    deleted_at      TIMESTAMP(6),
    CONSTRAINT uk_disclosures_receipt_no UNIQUE (receipt_no),
    CONSTRAINT fk_disclosures_stock      FOREIGN KEY (stock_id) REFERENCES stocks(id)
);
CREATE INDEX IF NOT EXISTS idx_disclosure_submitted_at      ON disclosures (submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_disclosure_stock_submitted   ON disclosures (stock_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_disclosure_type_submitted    ON disclosures (disclosure_type, submitted_at DESC);
